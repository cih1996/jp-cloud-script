// 获取所有国家列表（去重）
export function getCountryList(): { code: string; name: string }[] {
  const seen = new Set<string>()
  const result: { code: string; name: string }[] = []

  for (const [code] of allOperators) {
    if (!seen.has(code)) {
      seen.add(code)
      result.push({
        code,
        name: countryNames[code] || code.toUpperCase()
      })
    }
  }

  return result
}

// 根据国家代码获取运营商列表
export function getOperatorsByCountry(countryCode: string): { name: string; mcc: string; mnc: string }[] {
  return allOperators
    .filter(([code]) => code === countryCode)
    .map(([, name, mcc, mnc]) => ({ name, mcc, mnc }))
}
